create table company (
    id         bigint generated by default as identity primary key,
    name       varchar(200)  not null,
    website    varchar(500),
    notes      text,
    created_at timestamptz   not null
);

-- Company names are unique regardless of case ("ACME" and "Acme" are the same company).
create unique index company_name_uq on company (lower(name));

create table job_application (
    id             bigint generated by default as identity primary key,
    company_id     bigint        not null references company (id),
    role_title     varchar(200)  not null,
    job_url        varchar(1000),
    location       varchar(200),
    work_mode      varchar(20),
    source         varchar(100),
    status         varchar(20)   not null,
    applied_on     date,
    next_action    varchar(300),
    next_action_on date,
    notes          text,
    created_at     timestamptz   not null,
    updated_at     timestamptz   not null,
    version        bigint        not null default 0,
    constraint job_application_status_ck check (status in
        ('WISHLIST', 'APPLIED', 'SCREENING', 'INTERVIEWING', 'OFFER',
         'ACCEPTED', 'DECLINED', 'REJECTED', 'WITHDRAWN')),
    constraint job_application_work_mode_ck check (work_mode in ('ONSITE', 'HYBRID', 'REMOTE'))
);

create index job_application_company_idx on job_application (company_id);
create index job_application_status_idx on job_application (status);
create index job_application_next_action_idx on job_application (next_action_on)
    where next_action_on is not null;

-- Every status the application has been in, oldest first. The first row has no from_status.
create table status_change (
    id             bigint generated by default as identity primary key,
    application_id bigint       not null references job_application (id) on delete cascade,
    from_status    varchar(20),
    to_status      varchar(20)  not null,
    changed_on     date         not null,
    note           varchar(1000),
    recorded_at    timestamptz  not null
);

create index status_change_application_idx on status_change (application_id, id);
